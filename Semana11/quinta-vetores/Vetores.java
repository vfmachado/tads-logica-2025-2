public class Vetores {
    public static void main(String[] args) {
        
        String [] nomes;    // criando um ponteiro
        nomes = new String[10]; // nomes é um vetor de tamanho 10
        // podemos agora guardar 10 valores do tipo String na mesma variavel nomes

        nomes[0] = "Vinicius";
        nomes[1] = "Theodoro";
        nomes[2] = "Cristiana";

        System.out.println("TESTE");

        // todo vetor tem uma propriedade chamada LENGTH que contem o valor do seu tamanho.
        // nomes.length  será igual a 10 pq este vetor tem tamanho 10
        
    }
}
